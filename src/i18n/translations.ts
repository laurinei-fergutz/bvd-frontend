export type TranslationKey = keyof (typeof dictionaries)['pt'];

export function translate(language: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template: string = dictionaries[language][key] ?? dictionaries.pt[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (text: string, [name, value]) => text.split(`{{${name}}}`).join(String(value)),
    template,
  );
}
